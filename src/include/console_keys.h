#ifndef DDOS_CONSOLE_KEYS_H
#define DDOS_CONSOLE_KEYS_H

/* Non-ASCII keys carried by the DDOS console byte stream. */
enum {
    DDOS_KEY_F2 = 0x82, DDOS_KEY_F3, DDOS_KEY_F4 = 0x84,
    DDOS_KEY_UP = 0x90, DDOS_KEY_DOWN, DDOS_KEY_PAGE_UP, DDOS_KEY_PAGE_DOWN,
    DDOS_KEY_LEFT, DDOS_KEY_RIGHT, DDOS_KEY_HOME, DDOS_KEY_END, DDOS_KEY_DELETE,
    DDOS_KEY_CTRL_N, DDOS_KEY_CTRL_O, DDOS_KEY_CTRL_S,
};

#endif
